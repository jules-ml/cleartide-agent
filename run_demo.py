"""One-command class demo.

python run_demo.py
    Rebuild the isolated demo database, run the scenarios, refresh the
    offline backup, and print the transcript.

python run_demo.py --serve
    Same, then open the local dashboard. No API key and no network.
"""

import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DEMO_DB = ROOT / "data" / "demo_cleartide.db"
os.environ["CLEARTIDE_DB_PATH"] = str(DEMO_DB)

from demo.fixtures import CLASS_SCENARIOS
from demo.report_html import render_page
from demo.runner import run_class_scenarios
from demo.seed import build_demo_database
from src.audit import get_complete_audit_record


BACKUP_HTML = ROOT / "docs" / "backup" / "demo_report.html"
TRANSCRIPT = ROOT / "docs" / "backup" / "transcript.md"
EVAL_PATH = ROOT / "evals" / "synthetic_results.json"
TRACE_PATH = ROOT / "docs" / "traceability_results.json"


def _load_json(path: Path):
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _public_audit(record):
    if not record:
        return None
    decision = dict(record.get("decision") or {})
    decision.pop("_audit_notes", None)
    return {
        "decision_id": record.get("decision_id"),
        "decision": decision,
        "timeline": record.get("timeline") or [],
        "complete": record.get("complete"),
        "audit_notes": record.get("audit_notes") or [],
    }


def build_payload(scenario_views: list[dict]) -> dict:
    evaluation = _load_json(EVAL_PATH) or {}
    if "results" in evaluation:
        evaluation = {
            "generated_at_utc": evaluation.get("generated_at_utc"),
            "reasoning_mode": evaluation.get("reasoning_mode"),
            "summary": evaluation.get("summary"),
        }
    trace = _load_json(TRACE_PATH) or {}
    audits = {}
    decisions = []
    for view in scenario_views:
        record = _public_audit(get_complete_audit_record(view["decision_id"]))
        if record:
            audits[str(view["decision_id"])] = record
            decision = record["decision"]
            decisions.append(
                {
                    "decision_id": view["decision_id"],
                    "primary_intent": decision.get("primary_intent"),
                    "final_action": decision.get("final_action"),
                    "audit_status": decision.get("audit_status"),
                }
            )
    scenarios = []
    by_id = {view["scenario_id"]: view for view in scenario_views}
    for scenario in CLASS_SCENARIOS:
        item = dict(scenario)
        item["result"] = by_id.get(scenario["id"])
        scenarios.append(item)
    return {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "scenarios": scenarios,
        "decisions": decisions,
        "audits": audits,
        "evaluation": evaluation,
        "traceability": [
            row
            for row in (trace.get("requirements") or [])
            if str(row.get("requirement_id", "")).startswith("FR-")
        ],
    }


def write_transcript(views: list[dict]) -> None:
    lines = [
        "# Cleartide ACA backup transcript",
        "",
        "Generated by `python run_demo.py`. Figures in the evaluation file are separate and come from `python run_synthetic_evaluation.py`.",
        "",
    ]
    for view in views:
        lines.extend(
            [
                f"## {view['title']}",
                "",
                view.get("story") or "",
                "",
                f"- Customer: {view['reply_text']}",
                f"- Intent: {view['intent']} ({view['confidence']})",
                f"- Risk: {view['risk_band']} {view['risk_score']}",
                f"- Recommended: {view['recommended_action']} via {view['channel']}",
                f"- Verdict: {view['verdict']}",
                f"- Rule: {', '.join(view.get('violated_constraints') or []) or 'none'}",
                f"- Final: {view['final_status']} / {view['final_action']}",
                f"- Executed: {'Yes' if view['executed'] else 'No'}",
                f"- Decision id: {view['decision_id']}",
                "",
            ]
        )
        if view.get("mismatches"):
            lines.append("Mismatches: " + "; ".join(view["mismatches"]))
            lines.append("")
    TRANSCRIPT.parent.mkdir(parents=True, exist_ok=True)
    TRANSCRIPT.write_text("\n".join(lines), encoding="utf-8")


def main():
    build_demo_database(DEMO_DB)
    views = run_class_scenarios()
    mismatches = [item for item in views if item.get("mismatches")]
    for view in views:
        status = "OK" if not view["mismatches"] else "MISMATCH"
        print(f"{status}  {view['title']}: {view['verdict']} / {view['final_action']}")
        for mismatch in view["mismatches"]:
            print(f"    {mismatch}")
    payload = build_payload(views)
    BACKUP_HTML.parent.mkdir(parents=True, exist_ok=True)
    BACKUP_HTML.write_text(render_page(payload, live=False), encoding="utf-8")
    write_transcript(views)
    print(BACKUP_HTML)
    print(TRANSCRIPT)
    if mismatches:
        return 1
    if "--serve" in sys.argv:
        from demo.server import serve

        build_demo_database(DEMO_DB)
        serve(payload)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
